import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { cleanup, fireEvent, render, screen } from '@testing-library/react'
import JourneyCanvas from '../src/journal/JourneyCanvas.jsx'
vi.mock('../src/journal/Modal', () => ({ default: ({ children }) => <div role="dialog">{children}</div> }))
beforeEach(() => {
  vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} })
  localStorage.setItem('shitu-camera-v1', JSON.stringify({ x: 0, y: 0, scale: .55, detail: true }))
})
afterEach(() => { cleanup(); vi.unstubAllGlobals(); localStorage.clear() })
const fixture = count => ({ trips: [], marks: [], canvas_groups: [], entries: [{ id: 'e', components: [], entry_date: '2026-10-31', photos: Array.from({ length: count }, (_, i) => ({ id: `p${i}`, url: `/p${i}.jpg`, components: [], canvas_absolute: 1, canvas_x: (i % 20) * 18, canvas_y: Math.floor(i / 20) * 5 })) }] })
it.each([[500, 'desktop', 48, 120], [2000, 'tablet', 24, 60]])('bounds %i photos on %s without changing full selection or F navigation', (count, imageProfile, images, details) => {
  const onMove = vi.fn(), onMoveGroup = vi.fn()
  render(<JourneyCanvas data={fixture(count)} imageResidency imageProfile={imageProfile} onMove={onMove} onMoveGroup={onMoveGroup} />)
  const canvas = screen.getByRole('region')
  Object.defineProperties(canvas, { clientWidth: { value: 1000 }, clientHeight: { value: 700 } })
  expect(document.querySelectorAll('.j-photo')).toHaveLength(details)
  expect(document.querySelectorAll('.j-photo img')).toHaveLength(images)
  expect(document.querySelectorAll('.j-residency-overview').length).toBeGreaterThan(0)
  fireEvent.click(screen.getByRole('button', { name: '多选内容', exact: true }))
  fireEvent.keyDown(canvas, { key: 'a', ctrlKey: true })
  expect(screen.getByText(`已选 ${Math.min(500, count)} 项`)).toBeInTheDocument()
  expect(document.querySelectorAll('.j-photo').length).toBeLessThanOrEqual(details)
  expect(document.querySelectorAll('.j-photo img').length).toBeLessThanOrEqual(images)
  fireEvent.keyDown(canvas, { key: 'f' })
  expect(canvas).toHaveFocus()
  expect(onMove).not.toHaveBeenCalled(); expect(onMoveGroup).not.toHaveBeenCalled()
})
it('keeps default rendering and enables local overview camera navigation only when opted in', () => {
  const data = fixture(500), onMove = vi.fn()
  const { rerender } = render(<JourneyCanvas data={data} onMove={onMove} />)
  expect(document.querySelectorAll('.j-photo img')).toHaveLength(500)
  rerender(<JourneyCanvas data={data} imageResidency onMove={onMove} />)
  const before = document.querySelector('.j-world').style.transform
  fireEvent.click(document.querySelector('.j-residency-overview'))
  expect(document.querySelector('.j-world').style.transform).not.toBe(before)
  expect(onMove).not.toHaveBeenCalled()
})
it.each(['desktop', 'tablet'])('shares the %s budget across collapsed covers, notebooks and detailed cards', imageProfile => {
  const data = fixture(500)
  data.canvas_groups = Array.from({ length: 20 }, (_, i) => ({ id: `g${i}`, name: `group${i}`, collapsed: true, photo_ids: [`p${i * 3}`, `p${i * 3 + 1}`, `p${i * 3 + 2}`] }))
  data.notebooks = Array.from({ length: 30 }, (_, i) => ({ id: `b${i}`, name: `book${i}`, cover_url: `/b${i}.jpg`, canvas_x: i * 4, canvas_y: 100 }))
  render(<JourneyCanvas data={data} imageResidency imageProfile={imageProfile} />)
  expect(document.querySelectorAll('.j-world img').length).toBeLessThanOrEqual(imageProfile === 'desktop' ? 48 : 24)
  expect(document.querySelectorAll('.j-group-cover')).toHaveLength(20)
  expect(document.querySelectorAll('.j-notebook-cover').length).toBeLessThanOrEqual(30)
  expect(document.querySelectorAll('.j-image-placeholder').length).toBeGreaterThan(0)
})
it('retains a focused card node when a canvas pan moves it off screen', () => {
  render(<JourneyCanvas data={fixture(500)} imageResidency />)
  const canvas = screen.getByRole('region'), photo = document.querySelector('.j-photo')
  const captured = new Set()
  canvas.setPointerCapture = id => captured.add(id)
  canvas.hasPointerCapture = id => captured.has(id)
  canvas.releasePointerCapture = id => captured.delete(id)
  fireEvent.focus(photo)
  const pointer = (type, x) => {
    const event = new MouseEvent(type, { bubbles: true, button: 1, clientX: x, clientY: 100 })
    Object.defineProperty(event, 'pointerId', { value: 1 }); fireEvent(canvas, event)
  }
  pointer('pointerdown', 0); pointer('pointermove', 5000); pointer('pointerup', 5000)
  expect(document.querySelector(`[data-photo-id="${photo.dataset.photoId}"]`)).toBe(photo)
})
it.each([['desktop', 121, 120], ['tablet', 61, 60]])('caps %s mixed non-image nodes and keeps overflow reachable', (imageProfile, count, limit) => {
  const data = { trips: [], canvas_groups: [], entries: Array.from({ length: count }, (_, i) => ({ id: `e${i}`, entry_date: '2026-10-31', photos: [], mark: { id: `m${i}`, kind: 'text', text: 'note', canvas_x: i % 10, canvas_y: Math.floor(i / 10), width: 120, height: 100, font_size: 24 } })), notebooks: Array.from({ length: count }, (_, i) => ({ id: `b${i}`, name: `book${i}`, cover_mode: 'solid', canvas_x: i % 10, canvas_y: Math.floor(i / 10) })) }
  const onMove = vi.fn(), onMoveGroup = vi.fn()
  render(<JourneyCanvas data={data} imageResidency imageProfile={imageProfile} onMove={onMove} onMoveGroup={onMoveGroup} />)
  expect(document.querySelectorAll('[data-photo-id],.j-notebook-cover').length).toBeLessThanOrEqual(limit)
  expect(document.querySelectorAll('.j-world img')).toHaveLength(0)
  expect(document.querySelector('.j-residency-overview')).not.toBeNull()
  fireEvent.click(document.querySelector('.j-residency-overview'))
  expect(onMove).not.toHaveBeenCalled(); expect(onMoveGroup).not.toHaveBeenCalled()
})
it('opens max-zoom overlapping overflow through an explicit member choice', () => {
  localStorage.setItem('shitu-camera-v1', JSON.stringify({ x: 0, y: 0, scale: 2.4, detail: true }))
  const data = fixture(121), onOpen = vi.fn(), onMove = vi.fn()
  data.entries[0].photos.forEach(photo => { photo.canvas_x = 0; photo.canvas_y = 0 })
  render(<JourneyCanvas data={data} imageResidency onOpen={onOpen} onMove={onMove} />)
  fireEvent.click(document.querySelector('.j-residency-overview'))
  const member = document.querySelector('[data-member-id]')
  expect(member).not.toBeNull()
  fireEvent.click(member)
  expect(onOpen).toHaveBeenCalledWith(data.entries[0], member.dataset.memberId)
  expect(onMove).not.toHaveBeenCalled()
})
it('keeps a focused relative photo mounted when zoom-out returns to island mode', () => {
  const data = fixture(1)
  data.trips = [{ id: 'trip', name: '旅程', canvas_x: 0, canvas_y: 0 }]
  data.entries[0].trip_id = 'trip'; data.entries[0].photos[0].canvas_absolute = 0
  render(<JourneyCanvas data={data} imageResidency />)
  const photo = document.querySelector('[data-photo-id="p0"]')
  fireEvent.focus(photo)
  fireEvent.click(screen.getByRole('button', { name: '缩小画布' }))
  expect(document.querySelector('[data-photo-id="p0"]')).toBe(photo)
})
