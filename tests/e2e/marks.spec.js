import { test, expect } from '@playwright/test'

const created = new Set(), api = 'http://127.0.0.1:3001/api/journal'
test.afterEach(async ({ request }) => { for (const id of created) await request.delete(api + '/marks/' + id); created.clear() })

test('loose text and stickers save, drag, edit, reload and remain usable on a phone', async ({ page, request }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => localStorage.removeItem('shitu-camera-v1'))
  await page.goto('/')
  await expect(page.getByRole('button', { name: '随手写字', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '留下一刻', exact: true }).first().click()
  await page.getByRole('tab', { name: '文字', exact: true }).click()
  let editor = page.getByRole('tabpanel', { name: '文字', exact: true })
  await editor.getByLabel('想写什么？').fill('慢一点，\n风景在路上。')
  await page.getByRole('tab', { name: '照片', exact: true }).click()
  await expect(page.getByRole('tabpanel', { name: '照片', exact: true }).getByLabel('选择旅行照片')).toBeAttached()
  await page.getByRole('tab', { name: '文字', exact: true }).click()
  await expect(editor.getByLabel('想写什么？')).toHaveValue('慢一点，\n风景在路上。')
  await editor.getByRole('button', { name: '湖蓝', exact: true }).click()
  await editor.getByRole('button', { name: '大', exact: true }).click()
  await editor.getByLabel('标注角度').fill('-6')
  let saved = page.waitForResponse(response => response.url().endsWith('/journal/marks') && response.request().method() === 'POST')
  await editor.getByRole('button', { name: '放到手帐里', exact: true }).click()
  const textId = (await (await saved).json()).id; created.add(textId)
  await expect(editor).toBeHidden()
  const text = page.locator(`[data-kind="mark"][data-photo-id="${textId}"]`)
  await expect(text).toContainText('风景在路上。')
  expect(await text.evaluate(element => element.scrollHeight <= element.clientHeight)).toBe(true)
  const bounds = await text.boundingBox()
  saved = page.waitForResponse(response => response.url().endsWith('/journal/layout') && response.request().method() === 'PATCH')
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2 + 180, bounds.y + bounds.height / 2 + 80, { steps: 8 }); await page.mouse.up()
  expect((await saved).status()).toBe(200)
  const stored = (await (await request.get(api)).json()).marks.find(mark => mark.id === textId)
  expect(stored.canvas_x).not.toBe(0); expect(stored.rotation).toBe(-6)
  await page.getByRole('button', { name: '留下一刻', exact: true }).first().click()
  await page.getByRole('tab', { name: '贴纸', exact: true }).click()
  editor = page.getByRole('tabpanel', { name: '贴纸', exact: true })
  await editor.getByRole('button', { name: '小花贴纸', exact: true }).click()
  await editor.getByRole('button', { name: '玫瑰', exact: true }).click()
  saved = page.waitForResponse(response => response.url().endsWith('/journal/marks') && response.request().method() === 'POST')
  await editor.getByRole('button', { name: '放到手帐里', exact: true }).click()
  const stickerId = (await (await saved).json()).id; created.add(stickerId)
  await expect(editor).toBeHidden()
  await expect(page.locator(`[data-photo-id="${stickerId}"] svg`)).toHaveAttribute('aria-label', '小花')
  await page.screenshot({ path: 'test-results/marks-canvas.png' })
  await page.emulateMedia({ colorScheme: 'dark' })
  const textBackground = await text.locator('.is-text').evaluate(element => getComputedStyle(element).backgroundColor)
  expect(textBackground).not.toBe('rgba(0, 0, 0, 0)')
  expect(textBackground).not.toBe(await page.locator('.j-canvas').evaluate(element => getComputedStyle(element).backgroundColor))
  await page.screenshot({ path: 'test-results/marks-canvas-dark.png' })
  await page.emulateMedia({ colorScheme: 'light' })
  await page.reload()
  await text.click()
  editor = page.getByRole('dialog')
  await expect(editor.getByLabel('想写什么？')).toHaveValue('慢一点，\n风景在路上。')
  await editor.getByLabel('想写什么？').fill('这一站，想再来一次。')
  await editor.getByRole('button', { name: '保存标注', exact: true }).click()
  await expect(editor).toBeHidden()
  await expect(text).toContainText('这一站，想再来一次。')
  await page.setViewportSize({ width: 390, height: 844 })
  const mobileText = page.locator(`[data-mark-id="${textId}"]`), mobileSticker = page.locator(`[data-mark-id="${stickerId}"]`)
  await expect(mobileText).toContainText('这一站，想再来一次。')
  await expect(mobileSticker).toBeVisible()
  await page.getByRole('button', { name: '留下一刻', exact: true }).first().click()
  await page.getByRole('tab', { name: '文字', exact: true }).click()
  await expect(page.getByRole('tabpanel', { name: '文字', exact: true }).getByLabel('想写什么？')).toBeVisible()
  await page.screenshot({ path: 'test-results/add-memory-mobile.png' })
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await page.screenshot({ path: 'test-results/marks-mobile.png', fullPage: true })
  await mobileSticker.click()
  editor = page.getByRole('dialog')
  await expect(editor.getByRole('button', { name: '小花贴纸', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.screenshot({ path: 'test-results/marks-editor.png' })
  await editor.getByRole('button', { name: '删除标注', exact: true }).click()
  await editor.getByRole('button', { name: '确认删除', exact: true }).click()
  await expect(editor).toBeHidden()
  await expect(mobileSticker).toHaveCount(0)
  expect(await page.locator('body').evaluate(element => element.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
