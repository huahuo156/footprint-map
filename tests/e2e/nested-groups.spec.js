import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('nested blocks select atomically, persist, drag together and dissolve one layer', async ({ page, request }) => {
  const api = '/api/journal', groupIds = new Set()
  let entryId
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    const image = await readFile('public/journal-demo/west-lake.jpg')
    const form = new FormData()
    form.append('data', JSON.stringify({ components: [], photos: [0, 1, 2, 3].map(upload_index => ({ upload_index, components: [] })) }))
    for (let i = 0; i < 4; i++) form.append('images', new Blob([image], { type: 'image/jpeg' }), 'lake.jpg')
    const saved = await fetch('http://127.0.0.1:3001' + api + '/entries', { method: 'POST', body: form })
    expect(saved.status).toBe(201)
    entryId = (await saved.json()).id
    const entry = (await (await request.get(api)).json()).entries.find(entry => entry.id === entryId)
    const positions = entry.photos.map((photo, index) => ({ id: photo.id, x: -420 + index * 280, y: 0, rotation: 0 }))
    async function makeGroup(name, positions) {
      const result = await request.post(api + '/groups', { data: { name, color: 'sky', positions } })
      expect(result.status()).toBe(201)
      const group = await result.json(); groupIds.add(group.id); return group
    }
    const a = await makeGroup('测试内层甲', positions.slice(0, 2)), b = await makeGroup('测试内层乙', positions.slice(2))
    await page.route('**/api/journal', async route => {
      const response = await route.fetch(), data = await response.json()
      await route.fulfill({ response, json: { ...data, trips: [], marks: [], entries: data.entries.filter(entry => entry.id === entryId), canvas_groups: data.canvas_groups.filter(group => group.photo_ids.some(id => positions.some(photo => photo.id === id))) } })
    })
    await page.addInitScript(() => localStorage.setItem('shitu-camera-v1', JSON.stringify({ x: 0, y: 100, scale: .8, detail: true })))
    await page.goto('/')
    const photo = index => page.locator(`[data-photo-id="${positions[index].id}"]`)
    await page.getByRole('button', { name: '多选内容', exact: true }).click()
    const groupBox = await page.locator(`[data-group-id="${a.id}"]`).boundingBox()
    await page.mouse.move(groupBox.x - 10, groupBox.y - 10); await page.mouse.down()
    await page.mouse.move(groupBox.x + 10, groupBox.y + 10, { steps: 5 }); await page.mouse.up()
    await expect(photo(0)).toHaveAttribute('aria-pressed', 'true')
    await expect(photo(1)).toHaveAttribute('aria-pressed', 'true')
    await expect(photo(2)).toHaveAttribute('aria-pressed', 'false')
    await page.getByRole('button', { name: '清空选择', exact: true }).click()
    await photo(0).click()
    await expect(photo(1)).toHaveAttribute('aria-pressed', 'true')
    await page.getByRole('button', { name: '移动分组：测试内层乙' }).click()
    async function wrap(name) {
      await page.getByRole('button', { name: '添加色块分组', exact: true }).click()
      await page.getByLabel('组名', { exact: true }).fill(name)
      const saved = page.waitForResponse(response => response.url().endsWith('/journal/groups') && response.request().method() === 'POST')
      await page.getByRole('button', { name: '保存分组', exact: true }).click()
      const response = await saved; expect(response.status()).toBe(201)
      const group = await response.json(); groupIds.add(group.id)
      await expect(page.getByRole('dialog')).toBeHidden()
      return group
    }
    const outer = await wrap('测试外层')
    await page.reload()
    await expect(page.locator(`[data-group-id="${a.id}"]`)).toHaveAttribute('data-parent-group-id', outer.id)
    await page.getByRole('button', { name: '多选内容', exact: true }).click()
    await photo(0).click()
    for (let i = 0; i < 4; i++) await expect(photo(i)).toHaveAttribute('aria-pressed', 'true')
    const top = await wrap('测试最外层')
    const handle = page.getByRole('button', { name: '移动分组：测试最外层' })
    const before = await photo(0).boundingBox(), childBefore = await page.locator(`[data-group-id="${a.id}"]`).boundingBox()
    const box = await handle.boundingBox()
    const moved = page.waitForResponse(response => response.url().endsWith('/journal/layout') && response.request().method() === 'PATCH')
    await page.mouse.move(box.x + 30, box.y + box.height / 2); await page.mouse.down()
    await page.mouse.move(box.x + 90, box.y + box.height / 2 + 40, { steps: 8 }); await page.mouse.up()
    expect((await moved).status()).toBe(200)
    const after = await photo(0).boundingBox(), childAfter = await page.locator(`[data-group-id="${a.id}"]`).boundingBox()
    expect(after.x - before.x).toBeCloseTo(60, 0)
    expect(childAfter.x - childBefore.x).toBeCloseTo(60, 0)
    // Folding preserves inner state and all stored photo coordinates, including after reload.
    const storedPhotos = async () => (await (await request.get(api)).json()).entries.find(entry => entry.id === entryId).photos
    const beforeFold = await storedPhotos()
    await page.getByRole('button', { name: '折叠分组：测试内层甲', exact: true }).click()
    await expect(photo(0)).toHaveCount(0)
    await page.getByRole('button', { name: '折叠分组：测试最外层', exact: true }).click()
    await expect(photo(2)).toHaveCount(0)
    const coverBeforeReload = await page.locator(`[data-group-id="${top.id}"]`).boundingBox()
    await page.reload()
    const foldedTop = page.locator(`[data-group-id="${top.id}"]`)
    await expect(foldedTop).toHaveClass(/is-collapsed/)
    const coverAfterReload = await foldedTop.boundingBox()
    expect(coverAfterReload.x).toBeCloseTo(coverBeforeReload.x, 0)
    expect(coverAfterReload.y).toBeCloseTo(coverBeforeReload.y, 0)
    await expect(page.locator(`[data-group-id="${outer.id}"]`)).toHaveCount(0)
    await expect(foldedTop.locator('.j-group-cover img')).toHaveCount(3)
    expect(await storedPhotos()).toEqual(beforeFold)
    // A folded cover still participates in whole-group selection and nesting.
    await page.getByRole('button', { name: '多选内容', exact: true }).click()
    await page.getByRole('button', { name: '移动分组封面：测试最外层', exact: true }).click()
    await expect(page.getByText('已选 4 项', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '结束多选', exact: true }).click()
    const cover = page.getByRole('button', { name: '移动分组封面：测试最外层', exact: true })
    const coverBox = await cover.boundingBox(), foldedBox = await foldedTop.boundingBox()
    const movedFold = page.waitForResponse(response => response.url().endsWith('/journal/layout') && response.request().method() === 'PATCH')
    await page.mouse.move(coverBox.x + 20, coverBox.y + 20); await page.mouse.down()
    await page.mouse.move(coverBox.x + 60, coverBox.y + 40, { steps: 8 }); await page.mouse.up()
    expect((await movedFold).status()).toBe(200)
    expect((await foldedTop.boundingBox()).x - foldedBox.x).toBeCloseTo(40, 0)
    const afterFoldMove = await storedPhotos()
    for (const photo of afterFoldMove) {
      const previous = beforeFold.find(old => old.id === photo.id)
      expect(photo.canvas_x - previous.canvas_x).toBeCloseTo(50, 2)
      expect(photo.canvas_y - previous.canvas_y).toBeCloseTo(25, 2)
    }
    await expect.poll(() => foldedTop.locator('img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0))).toBe(true)
    await page.screenshot({ path: 'test-results/collapsed-groups.png', fullPage: true })
    // Failed updates leave the saved cover visible and allow retry.
    await page.route('**/api/journal/groups/' + top.id, route => route.fulfill({ status: 503, json: { error: '折叠状态未保存，请重试' } }))
    await page.getByRole('button', { name: '展开分组：测试最外层', exact: true }).click()
    await expect(page.getByRole('status')).toContainText('折叠状态未保存，请重试')
    await expect(foldedTop).toHaveClass(/is-collapsed/)
    await page.unroute('**/api/journal/groups/' + top.id)
    await page.getByRole('button', { name: '展开分组：测试最外层', exact: true }).click()
    await expect(page.getByRole('button', { name: '展开分组：测试内层甲', exact: true })).toBeVisible()
    await expect(photo(0)).toHaveCount(0)
    await expect(photo(2)).toBeVisible()
    expect(await storedPhotos()).toEqual(afterFoldMove)
    await page.reload()
    await expect(page.locator(`[data-group-id="${outer.id}"]`)).toHaveAttribute('data-parent-group-id', top.id)
    await page.screenshot({ path: 'test-results/nested-groups.png', fullPage: true })
    await page.getByRole('button', { name: '编辑分组：测试最外层' }).click()
    await page.getByRole('button', { name: '解除分组', exact: true }).click()
    await expect(page.getByRole('dialog')).toBeHidden()
    await expect(page.locator(`[data-group-id="${top.id}"]`)).toHaveCount(0)
    await expect(page.locator(`[data-group-id="${a.id}"]`)).toHaveAttribute('data-parent-group-id', outer.id)
    await expect(page.locator(`[data-group-id="${b.id}"]`)).toBeVisible()
    expect(errors).toEqual([])
  } finally {
    for (const id of [...groupIds].reverse()) await request.delete(api + '/groups/' + id)
    if (entryId) await request.delete(api + '/entries/' + entryId)
  }
})
