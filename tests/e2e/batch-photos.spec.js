  await Promise.all(responses)
  const imported = (await (await request.get(api)).json()).entries.filter(entry => entries.has(entry.id)).flatMap(entry => entry.photos)
  const ids = imported.slice(0, 2).map(photo => photo.id)
  await page.getByRole('button', { name: '多选内容', exact: true }).click()
  await expect(page.getByRole('button', { name: '删除选中内容', exact: true })).toBeDisabled()
