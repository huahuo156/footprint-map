  const dialog = page.getByRole('dialog', { name: '删除 2 项内容？', exact: true })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '保留内容', exact: true }).click()
  await expect(dialog).toBeHidden()
  expect((await (await request.get(api)).json()).entries.filter(entry => entries.has(entry.id)).flatMap(entry => entry.photos)).toHaveLength(21)
  let attempts = 0
  await page.route('**/api/journal/items', async route => {
    if (route.request().method() === 'DELETE' && ++attempts === 1) return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '测试删除失败' }) })
    return route.continue()
  })
  await page.getByRole('button', { name: '删除选中内容', exact: true }).click()
  await dialog.getByRole('button', { name: '确认删除 2 项', exact: true }).click()
