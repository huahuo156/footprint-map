import { test, expect } from '@playwright/test'
import { createDatabasePool } from '../../server/db.js'
const pool = createDatabasePool()

const api = 'http://127.0.0.1:3001/api/journal', entries = new Set(), trips = new Set(), marks = new Set()
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+j2ioAAAAASUVORK5CYII=', 'base64')
const files = count => Array.from({ length: count }, (_, i) => ({ name: 'batch-' + i + '.png', mimeType: 'image/png', buffer: png }))
test.beforeEach(async ({ page, request }) => {
  const existing = await (await request.get(api)).json()
  const entryIds = new Set(existing.entries.map(entry => entry.id)), tripIds = new Set(existing.trips.map(trip => trip.id)), markIds = new Set(existing.marks.map(mark => mark.id))
  await page.route('**/api/journal', async route => {
    const response = await route.fetch(), data = await response.json()
    await route.fulfill({ response, json: { ...data, entries: data.entries.filter(entry => !entryIds.has(entry.id)), trips: data.trips.filter(trip => !tripIds.has(trip.id)), marks: data.marks.filter(mark => !markIds.has(mark.id)) } })
  })
})
test.afterEach(async ({ request }) => {
  for (const id of marks) await request.delete(api + '/marks/' + id)
  for (const id of entries) await request.delete(api + '/entries/' + id)
  for (const id of trips) await pool.execute('DELETE FROM journal_trips WHERE id=?', [id])
  entries.clear(); trips.clear(); marks.clear()
})
test.afterAll(async () => { await pool.end() })
function observe(page) {
  const responses = []
  page.on('response', response => {
    if (response.request().method() !== 'POST' || !response.ok()) return
    if (response.url().endsWith('/journal/entries')) responses.push(response.json().then(data => { entries.add(data.id); return data.id }))
    if (response.url().endsWith('/journal/trips')) responses.push(response.json().then(data => { trips.add(data.id) }))
  })
  return responses
}

