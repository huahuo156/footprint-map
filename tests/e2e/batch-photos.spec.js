test('an interrupted large import retries only photos not yet imported', async ({ page, request }) => {
  const responses = observe(page)
  let chunk = 0
  await page.route('**/api/journal/entries', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    if (++chunk === 2) return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: '测试中断' }) })
    return route.continue()
  })
  await page.goto('/')
  await page.getByRole('button', { name: '留下一刻', exact: true }).first().click()
  await page.getByLabel('批量导入照片', { exact: true }).setInputFiles(files(23))
  await expect(page.getByRole('alert')).toContainText('已导入 20 张')
  await page.getByRole('button', { name: '重试剩余 3 张', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await Promise.all(responses)
  const imported = (await (await request.get(api)).json()).entries.filter(entry => entries.has(entry.id)).flatMap(entry => entry.photos)
  expect(imported).toHaveLength(23)
  expect(chunk).toBe(3)
})

test('invalid images are named and skipped while valid photos continue importing once', async ({ page, request }) => {
  const responses = observe(page), input = files(23)
  input.splice(1, 0, { name: 'broken-memory.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('not an image') })
  // The browser reports JPEG from the extension; the server must recognize the real PNG.
  input[3] = { name: 'actually-png.jpg', mimeType: 'image/jpeg', buffer: png }
  await page.goto('/')
  await page.getByRole('button', { name: '留下一刻', exact: true }).first().click()
  await page.getByLabel('批量导入照片', { exact: true }).setInputFiles(input)
  const report = page.locator('.j-import-report')
  await expect(report).toContainText('已导入 23 张照片，1 个文件未导入。')
  await expect(report).toContainText('broken-memory.jpg')
  await expect(report).toContainText('未识别为 JPG、PNG 或 WebP')
  await expect(page.getByRole('button', { name: /重试剩余/ })).toHaveCount(0)
  await Promise.all(responses)
  const imported = (await (await request.get(api)).json()).entries.filter(entry => entries.has(entry.id)).flatMap(entry => entry.photos)
  expect(imported).toHaveLength(23)
  expect(new Set(imported.map(photo => photo.id)).size).toBe(23)
  expect(imported.every(photo => photo.url.endsWith('.png'))).toBe(true)
  await page.screenshot({ path: 'test-results/import-skipped-files.png' })
  await page.getByRole('button', { name: '查看已导入照片', exact: true }).click()
  await expect(page.getByRole('dialog')).toBeHidden()
})

