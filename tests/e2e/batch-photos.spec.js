  expect((await (await request.get(api)).json()).entries.filter(entry => entries.has(entry.id)).flatMap(entry => entry.photos)).toHaveLength(21)
  await page.screenshot({ path: 'test-results/batch-delete-confirm.png' })
  await dialog.getByRole('button', { name: '确认删除 2 项', exact: true }).click()
  await expect(dialog).toBeHidden()
  const remaining = (await (await request.get(api)).json()).entries.filter(entry => entries.has(entry.id)).flatMap(entry => entry.photos)
  expect(remaining).toEqual(imported.filter(photo => !ids.includes(photo.id)))
