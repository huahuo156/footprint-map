import { test, expect } from '@playwright/test'

test('notebook reuses composer, preserves mixed content and turns actual pages', async ({ page, request }) => {
  const errors = [], entryIds = [], markIds = []
  page.on('pageerror', error => errors.push(error.message))
  let bookId
  try {
    await page.goto('/')
    await page.getByRole('button', { name: '创建手札', exact: true }).first().click()
    await page.getByLabel('手札名称').fill('e2e-江南慢游')
    const created = page.waitForResponse(r => r.url().endsWith('/journal/notebooks') && r.request().method() === 'POST')
    await page.getByRole('button', { name: '保存手札' }).click()
    bookId = (await (await created).json()).id
    const reader = page.locator('.nb-reader')
    await expect(reader).toBeVisible()
    await expect(reader.getByLabel('手帐页码')).toHaveText('扉页 / 4')
    await reader.getByLabel('手札工具').click()
    await reader.getByRole('button', { name: '添加照片、文字或贴纸' }).click()
    const composer = page.getByRole('dialog', { name: '留下一刻', exact: true })
    await composer.getByLabel('选择旅行照片').setInputFiles(['public/journal-demo/west-lake.jpg', 'public/journal-demo/wuzhen.jpg'])
    await composer.getByRole('button', { name: '添加描述', exact: true }).click()
    await composer.getByLabel('想记住的事情').fill('那天下午的风很好。')
    const saved = page.waitForResponse(r => r.url().endsWith('/journal/entries') && r.request().method() === 'POST')
    await composer.getByRole('button', { name: '留下', exact: true }).click()
    entryIds.push((await (await saved).json()).id)
    await expect(composer).toHaveCount(0)
    await expect(reader.locator('.nb-spread [data-kind="photo"]')).toHaveCount(2)
    await expect(page.locator('.j-canvas [data-kind="photo"]')).toHaveCount(0)
    const boxes = await reader.locator('.nb-spread [data-kind="photo"]').evaluateAll(nodes => nodes.map(n => { const b = n.getBoundingClientRect(); return { x:b.x,y:b.y,w:b.width,h:b.height } }))
    expect(Math.abs(boxes[0].x-boxes[1].x)>=Math.min(boxes[0].w,boxes[1].w) || Math.abs(boxes[0].y-boxes[1].y)>=Math.min(boxes[0].h,boxes[1].h)).toBeTruthy()
    await page.screenshot({ path: 'test-results/notebook-shared-content.png' })
    await reader.getByRole('button', { name: '翻到下一张纸' }).click()
    await expect(reader.getByLabel('手帐页码')).toHaveText('3–4 / 4', { timeout: 15000 })
    await reader.getByRole('button', { name: '翻到上一张纸' }).click()
    await expect(reader.getByLabel('手帐页码')).toHaveText('1–2 / 4', { timeout: 15000 })
    await reader.getByLabel('合上手札').click()
    await page.reload()
    await page.getByRole('button', { name: '打开手帐：e2e-江南慢游' }).click()
    await expect(reader.locator('.nb-spread [data-kind="photo"]')).toHaveCount(2)
    await reader.getByLabel('手札工具').click()
    await reader.getByRole('button', { name: '添加照片、文字或贴纸' }).click()
    await composer.getByRole('tab', { name: '文字', exact: true }).click()
    await composer.locator('[data-add-pane="text"] textarea').fill('沿着湖边慢慢走。')
    const markSaved = page.waitForResponse(r => r.url().endsWith('/journal/marks') && r.request().method() === 'POST')
    await composer.getByRole('button', { name: '放到手帐里' }).click()
    markIds.push((await (await markSaved).json()).id)
    await expect(reader.locator('.nb-spread [data-kind="mark"]')).toHaveCount(1)
    await reader.locator('.nb-spread [data-notebook-page]').first().click({position:{x:30,y:70}})
    await reader.getByRole('button',{name:'夹住第1页'}).click()
    await expect(reader.getByRole('button',{name:'取下第1页的书签'})).toBeEnabled()
    await reader.getByRole('button',{name:'翻到下一张纸'}).click()
    await expect(reader.getByLabel('手帐页码')).toHaveText('3–4 / 4',{timeout:15000})
    await expect.poll(async()=>{
      const journal=await (await request.get('/api/journal')).json()
      const book=journal.notebooks.find(b=>b.id===bookId)
      return journal.notebook_pages.find(p=>p.id===book.last_read_page_id)?.sort_order
    }).toBe(3)
    await reader.getByLabel('合上手札').click()
    await page.reload()
    await page.getByRole('button', { name: '打开手帐：e2e-江南慢游' }).click()
    await expect(reader.getByLabel('手帐页码')).toHaveText('3–4 / 4')
    await reader.getByRole('button',{name:'翻到书签，第1页'}).click()
    await expect(reader.getByLabel('手帐页码')).toHaveText('1–2 / 4',{timeout:15000})
    await expect(reader.locator('.nb-spread [data-kind="photo"]')).toHaveCount(2)
    expect(errors).toEqual([])
  } finally {
    if (bookId) await request.delete('/api/journal/notebooks/' + bookId)
    for (const id of entryIds) await request.delete('/api/journal/entries/' + id)
    for (const id of markIds) await request.delete('/api/journal/marks/' + id)
  }
})

