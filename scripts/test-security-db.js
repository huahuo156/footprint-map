// Creates a fresh, disposable database; never runs tests against the configured personal DB.
import 'dotenv/config'
import mysql from 'mysql2/promise'
import { randomBytes, randomUUID } from 'node:crypto'
import { mkdtemp, rm, readFile, writeFile } from 'node:fs/promises'
import assert from 'node:assert/strict'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { spawn } from 'node:child_process'
const databaseName = 'footprint_security_test_' + randomBytes(6).toString('hex')
const uploads = await mkdtemp(path.join(tmpdir(), 'shitu-security-'))
const admin = await mysql.createConnection({ host: process.env.MYSQL_HOST || '127.0.0.1', port: Number(process.env.MYSQL_PORT || 3307), user: process.env.TEST_MYSQL_ADMIN_USER || 'root', password: process.env.TEST_MYSQL_ADMIN_PASSWORD || process.env.MYSQL_ROOT_PASSWORD })
async function cleanup() {
  // Both targets were generated by this process, and must remain within these bounds.
  if (!/^footprint_security_test_[a-f0-9]{12}$/.test(databaseName)) throw new Error('Invalid disposable database name')
  const resolved = path.resolve(uploads), root = path.resolve(tmpdir()) + path.sep
  if (!resolved.startsWith(root) || !path.basename(resolved).startsWith('shitu-security-')) throw new Error('Invalid disposable upload directory')
  try { await admin.query(`DROP DATABASE IF EXISTS ${mysql.escapeId(databaseName)}`) }
  finally { await admin.end(); await rm(resolved, { recursive: true, force: true }) }
}
try {
  await admin.query(`CREATE DATABASE ${mysql.escapeId(databaseName)} CHARACTER SET utf8mb4`)
  process.env.MYSQL_DATABASE = databaseName
  process.env.MYSQL_USER = process.env.TEST_MYSQL_ADMIN_USER || 'root'
  process.env.MYSQL_PASSWORD = process.env.TEST_MYSQL_ADMIN_PASSWORD || process.env.MYSQL_ROOT_PASSWORD
  process.env.UPLOAD_DIRECTORY = uploads
  process.env.APP_ORIGIN = 'http://localhost:4173'
  process.env.OPERATIONS_TOKEN = 'isolated-operations-token-' + randomBytes(16).toString('hex')
  const { pool, initializeDatabase } = await import('../server/db.js')
  try {
    await initializeDatabase()
    const schema = await readFile(new URL('../server/auth-schema.sql', import.meta.url), 'utf8')
    for (const sql of schema.split(';').filter(value => value.trim())) await pool.query(sql)
    const { migrateOwnership } = await import('../server/migrate-ownership.js')
    const { migrateLayoutVersions } = await import('../server/migrate-layout-versions.js')
    const connection = await pool.getConnection()
    try {
      const oldTrip = randomUUID(), designated = randomUUID(), firstSignup = randomUUID()
      await connection.execute('INSERT INTO journal_trips (id,name) VALUES (?,?)', [oldTrip, 'explicit legacy fixture'])
      await connection.execute('INSERT INTO users (id,email,password_hash) VALUES (?,?,?)', [firstSignup, 'first@example.com', 'not-a-login-hash'])
      await writeFile(path.join(uploads, 'legacy-orphan.png'), Buffer.from('private legacy placeholder'))
      await assert.rejects(migrateOwnership(connection, { uploadDirectory: uploads }), /legacy-owner/)
      await connection.execute('INSERT INTO users (id,email,password_hash) VALUES (?,?,?)', [designated, 'legacy@example.com', 'not-a-login-hash'])
      await migrateOwnership(connection, { legacyOwnerEmail: 'legacy@example.com', uploadDirectory: uploads })
      await migrateOwnership(connection, { uploadDirectory: uploads })
      await writeFile(path.join(uploads, 'unattached-cover.png'), Buffer.from('private registered placeholder'))
      await connection.execute('INSERT INTO assets (storage_key,owner_id,bytes,mime) VALUES (?,?,?,?)', ['unattached-cover.png', firstSignup, 30, 'image/png'])
      await migrateOwnership(connection, { legacyOwnerEmail: 'legacy@example.com', uploadDirectory: uploads })
      const [[unattached]] = await connection.execute('SELECT owner_id FROM assets WHERE storage_key=?', ['unattached-cover.png'])
      assert.equal(unattached.owner_id, firstSignup)
      const [[trip]] = await connection.execute('SELECT owner_id FROM journal_trips WHERE id=?', [oldTrip])
      const [[asset]] = await connection.execute('SELECT owner_id FROM assets WHERE storage_key=?', ['legacy-orphan.png'])
      assert.equal(trip.owner_id, designated); assert.equal(asset.owner_id, designated)
      await migrateLayoutVersions(connection)
      console.log('Legacy migration: explicit account required, no first-signup claim, repeat-safe.')
    } finally { connection.release() }
  } finally { await pool.end() }
  const arguments_ = process.argv.includes('--e2e') ? ['scripts/real-ui-test.mjs'] : ['--test', '--test-concurrency=1', 'server/security.test.js']
  const child = spawn(process.execPath, arguments_, { stdio: 'inherit', env: { ...process.env, SECURITY_TEST_DATABASE: databaseName } })
  process.exitCode = await new Promise((resolve, reject) => { child.on('error', reject); child.on('exit', code => resolve(code ?? 1)) })
  if (!process.argv.includes('--e2e') && !process.exitCode) {
    const { runSystemBackupIntegration } = await import('./restore-drill.js')
    await runSystemBackupIntegration()
  }
} finally { await cleanup() }
